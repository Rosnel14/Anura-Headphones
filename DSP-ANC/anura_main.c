static void oled_send_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 10);
}

static void oled_init(void)
{
    HAL_Delay(100);
    const uint8_t cmds[] = {
        0xAE,             /* display off        */
        0xD5, 0x80,       /* clock divide       */
        0xA8, 0x3F,       /* multiplex 64       */
        0xD3, 0x00,       /* display offset 0   */
        0x40,             /* start line 0       */
        0x8D, 0x14,       /* charge pump on     */
        0x20, 0x00,       /* horizontal addr    */
        0xA1,             /* seg remap          */
        0xC8,             /* com scan direction */
        0xDA, 0x12,       /* com pins           */
        0x81, 0xCF,       /* contrast           */
        0xD9, 0xF1,       /* pre-charge         */
        0xDB, 0x40,       /* vcom detect        */
        0xA4,             /* all on resume      */
        0xA6,             /* normal display     */
        0xAF,             /* display on         */
    };
    for (uint32_t i = 0; i < sizeof(cmds); i++)
        oled_send_cmd(cmds[i]);
}

static void oled_clear(void)
{
    memset(oled_buf, 0, sizeof(oled_buf));
}

static void oled_draw_char(uint8_t col, uint8_t page, char c)
{
    if (c < 32 || c > 'z') c = ' ';
    const uint8_t *glyph = font5x7[c - 32];
    uint32_t idx = page * OLED_WIDTH + col;
    if (idx + 5 > sizeof(oled_buf)) return;
    for (uint8_t i = 0; i < 5; i++)
        oled_buf[idx + i] = glyph[i];
    oled_buf[idx + 5] = 0x00;   /* 1px spacing */
}

static void oled_draw_string(uint8_t col, uint8_t page, const char *str)
{
    while (*str && col < OLED_WIDTH) {
        oled_draw_char(col, page, *str++);
        col += 6;
    }
}

static void oled_flush(void)
{
    oled_send_cmd(0x21); oled_send_cmd(0); oled_send_cmd(127);  /* col 0-127  */
    oled_send_cmd(0x22); oled_send_cmd(0); oled_send_cmd(7);    /* page 0-7   */

    /* Send framebuffer in chunks of 32 bytes */
    uint8_t tx[33];
    tx[0] = 0x40;   /* data mode */
    for (uint32_t i = 0; i < sizeof(oled_buf); i += 32) {
        memcpy(&tx[1], &oled_buf[i], 32);
        HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, tx, 33, 10);
    }
}


/* ══════════════════════════════════════════════════════════
 *  BMS — generic placeholder, swap registers once chip confirmed
 * ══════════════════════════════════════════════════════════ */
static uint8_t bms_read_soc(void)
{
    uint8_t reg = BMS_REG_SOC;
    uint8_t val = 0;
    if (HAL_I2C_Master_Transmit(&hi2c1, BMS_I2C_ADDR, &reg, 1, 10) == HAL_OK)
        HAL_I2C_Master_Receive(&hi2c1, BMS_I2C_ADDR, &val, 1, 10);
    return val;   /* raw register — scale to % once chip confirmed */
}


/* ══════════════════════════════════════════════════════════
 *  OLED DISPLAY UPDATE
 * ══════════════════════════════════════════════════════════ */
static const char *mode_names[] = {
    "Passthrough",
    "Analog ANC",
    "Digital ANC",
    "Translation",
};

static void oled_update(void)
{
    char line[22];
    uint8_t soc = bms_read_soc();

    oled_clear();
    oled_draw_string(0, 0, "-- ANURA --");
    oled_draw_string(0, 2, "Mode:");
    oled_draw_string(0, 3, mode_names[current_mode]);
    snprintf(line, sizeof(line), "Battery: %d%%", soc);
    oled_draw_string(0, 5, line);
    oled_flush();
}


/* ══════════════════════════════════════════════════════════
 *  INIT
 * ══════════════════════════════════════════════════════════ */
void anura_init(void)
{
    lms_init(&lms_left);
    lms_init(&lms_right);

    /* Start in passthrough, digital path */
    current_mode = MODE_PASSTHROUGH;
    set_ad_ctrl(1);

    /* OLED */
    oled_init();
    oled_update();

    /* ADC DMA — 4 channels, circular, timer-triggered */
    HAL_ADC_Start_DMA(&hadc1, (uint32_t *)adc_buf, ADC_BUF_LEN);

    /* DAC DMA — dual channel */
    HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_1,
                      (uint32_t *)dac_buf,
                      ADC_BUF_FRAMES, DAC_ALIGN_12B_R);
    HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_2,
                      (uint32_t *)&dac_buf[0].right,
                      ADC_BUF_FRAMES, DAC_ALIGN_12B_R);

    /* Sample rate timer */
    HAL_TIM_Base_Start(&htim2);

    /* Button debounce timer */
    HAL_TIM_Base_Start_IT(&htim4);
}


/* ══════════════════════════════════════════════════════════
 *  MAIN LOOP — call anura_init() then anura_run() from main()
 * ══════════════════════════════════════════════════════════ */
void anura_run(void)
{
    uint32_t last_display_tick = 0;

    while (1) {
        /* Check button — switches mode if debounced press detected */
        AnuraMode prev = current_mode;
        button_check();

        /* Refresh OLED every 500ms or on mode change */
        uint32_t now = HAL_GetTick();
        if (current_mode != prev || (now - last_display_tick) >= 500) {
            oled_update();
            last_display_tick = now;
        }

        /* Audio processing happens entirely in DMA callbacks —
         * nothing audio-related needed here in the main loop. */
    }
}


/* ══════════════════════════════════════════════════════════
 *  CubeMX CONFIGURATION CHECKLIST
 * ──────────────────────────────────────────────────────────
 *
 *  ADC1  Scan mode, 4 channels, right-align, 12-bit
 *    Rank 1  IN2  (PA2)  84 cycles  ← left outer MEMS mic
 *    Rank 2  IN3  (PA3)  84 cycles  ← right outer MEMS mic
 *    Rank 3  IN6  (PA6)  84 cycles  ← left audio in
 *    Rank 4  IN7  (PA7)  84 cycles  ← right audio in
 *    External trigger: TIM2 TRGO, rising edge
 *    DMA: DMA2 Stream0 Ch0, circular, HalfWord→HalfWord
 *    Enable DMA half-transfer + transfer-complete interrupts
 *
 *  DAC
 *    Ch1 (PA4): trigger TIM2 TRGO, DMA1 Stream5 Ch7, output buffer ON
 *    Ch2 (PA5): trigger TIM2 TRGO, DMA1 Stream6 Ch7, output buffer ON
 *
 *  TIM2  (sample rate)
 *    Internal clock, prescaler 0
 *    ARR = 1749  → 84MHz / 1750 = 48kHz
 *    TRGO: Update event
 *
 *  TIM3  (PWM mono mic out)
 *    CH3 on PB0, PWM mode 1
 *    Prescaler 0, ARR = 4095
 *    CCR3 set dynamically in firmware
 *
 *  TIM4  (button debounce)
 *    Internal clock, prescaler 83, ARR = 999
 *    → 84MHz / 84 / 1000 = 1kHz = 1ms tick
 *    Enable update interrupt in NVIC
 *
 *  I2C1
 *    PB6 SCL, PB7 SDA
 *    Fast mode 400kHz
 *
 *  GPIO
 *    PA8: GPIO_Input, Pull-Down  ← mode button
 *    PB4: GPIO_Output, Push-Pull, no pull, init LOW
 *
 *  NVIC priorities
 *    DMA2_Stream0: 0 (highest — audio ISR)
 *    TIM4:         1 (button debounce)
 *    I2C1:         2
 * ══════════════════════════════════════════════════════════ */
