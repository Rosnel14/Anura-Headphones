/* ══════════════════════════════════════════════════════════
 *  TUNEABLE PARAMETERS
 * ══════════════════════════════════════════════════════════ */
#define ANC_FILTER_TAPS         64
#define ANC_MU                  0.005f
#define ANC_BLOCK_SIZE          32
#define SAMPLE_RATE             48000

#define ADC_MIDPOINT            2048
#define ADC_SCALE               (1.0f / 2048.0f)
#define DAC_MIDPOINT            2048
#define DAC_SCALE               2047.0f

#define NLMS_BETA               0.999f
#define NLMS_EPSILON            1e-4f

#define PWM_PERIOD              4095

#define BUTTON_DEBOUNCE_MS      50
#define NUM_MODES               4

/* ── I2C addresses ────────────────────────────────────────
 * SSD1306 OLED: 0x3C (7-bit) → 0x78 shifted
 * BMS: replace 0x6B with your actual chip address once confirmed
 * ───────────────────────────────────────────────────────── */
#define OLED_I2C_ADDR           (0x3C << 1)
#define BMS_I2C_ADDR            (0x6B << 1)   /* TODO: confirm with power PCB */

/* BMS register placeholders — swap in real addresses once chip confirmed */
#define BMS_REG_SOC             0x00   /* state of charge (%) */
#define BMS_REG_VOLTAGE         0x01   /* battery voltage      */

/* ══════════════════════════════════════════════════════════
 *  ADC / DAC BUFFER TYPES
 * ══════════════════════════════════════════════════════════ */
/* 4 ADC channels: ref_l, ref_r, src_l, src_r */
typedef struct {
    uint16_t ref_l;    /* PA2 ADC1_IN2  outer MEMS mic left  (FF ref)  */
    uint16_t ref_r;    /* PA3 ADC1_IN3  outer MEMS mic right (FF ref)  */
    uint16_t src_l;    /* PA6 ADC1_IN6  source audio L + error ref     */
    uint16_t src_r;    /* PA7 ADC1_IN7  source audio R + error ref     */
} AdcFrame;

typedef struct {
    uint16_t left;
    uint16_t right;
} DacFrame;

#define ADC_CHANNELS            4
#define ADC_BUF_FRAMES          (ANC_BLOCK_SIZE * 2)
#define ADC_BUF_LEN             (ADC_BUF_FRAMES * ADC_CHANNELS)

static AdcFrame adc_buf[ADC_BUF_FRAMES];
static DacFrame dac_buf[ADC_BUF_FRAMES];

/* ══════════════════════════════════════════════════════════
 *  MODE STATE
 * ══════════════════════════════════════════════════════════ */
typedef enum {
    MODE_PASSTHROUGH  = 0,
    MODE_ANALOG_ANC   = 1,
    MODE_DIGITAL_ANC  = 2,
    MODE_TRANSLATION  = 3
} AnuraMode;

static volatile AnuraMode current_mode = MODE_PASSTHROUGH;

/* ══════════════════════════════════════════════════════════
 *  LMS FILTER STATE
 * ══════════════════════════════════════════════════════════ */
typedef struct {
    float32_t weights[ANC_FILTER_TAPS];
    float32_t delay[ANC_FILTER_TAPS];
    uint32_t  head;
    float32_t power;
} LmsChannel;

static LmsChannel lms_left;
static LmsChannel lms_right;

/* ══════════════════════════════════════════════════════════
 *  HAL HANDLES (generated by CubeMX in main.c)
 * ══════════════════════════════════════════════════════════ */
extern ADC_HandleTypeDef  hadc1;
extern DAC_HandleTypeDef  hdac;
extern TIM_HandleTypeDef  htim2;   /* sample rate trigger  */
extern TIM_HandleTypeDef  htim3;   /* PWM mono mic out     */
extern TIM_HandleTypeDef  htim4;   /* 1ms button debounce  */
extern I2C_HandleTypeDef  hi2c1;   /* OLED + BMS           */


/* ══════════════════════════════════════════════════════════
 *  CONVERSION HELPERS
 * ══════════════════════════════════════════════════════════ */
static inline float32_t adc_to_float(uint16_t raw)
{
    return (float32_t)((int32_t)raw - ADC_MIDPOINT) * ADC_SCALE;
}

static inline uint16_t float_to_dac(float32_t s)
{
    if      (s >  1.0f) s =  1.0f;
    else if (s < -1.0f) s = -1.0f;
    return (uint16_t)((int32_t)(s * DAC_SCALE) + DAC_MIDPOINT);
}


/* ══════════════════════════════════════════════════════════
 *  LMS / NLMS
 * ══════════════════════════════════════════════════════════ */
static void lms_init(LmsChannel *ch)
{
    memset(ch->weights, 0, sizeof(ch->weights));
    memset(ch->delay,   0, sizeof(ch->delay));
    ch->head  = 0;
    ch->power = 1.0f;
}

/*
 * lms_process — feedforward NLMS step
 *
 * x : feedforward reference (outer MEMS mic)
 * e : error reference (audio_in — what leaked into ear after speaker output)
 *     Since we have no inner mic, we use the source audio signal as a
 *     proxy error: once ANC converges, src should contain mostly speech.
 *
 * returns: predicted anti-noise sample
 */
static float32_t lms_process(LmsChannel *ch, float32_t x, float32_t e)
{
    ch->delay[ch->head] = x;

    float32_t y = 0.0f;
    uint32_t k = ch->head;
    for (uint32_t i = 0; i < ANC_FILTER_TAPS; i++) {
        y += ch->weights[i] * ch->delay[k];
        k  = (k == 0) ? (ANC_FILTER_TAPS - 1) : (k - 1);
    }

    ch->power = NLMS_BETA * ch->power + (1.0f - NLMS_BETA) * (x * x);
    float32_t mu_norm = ANC_MU / (ch->power + NLMS_EPSILON);

    k = ch->head;
    for (uint32_t i = 0; i < ANC_FILTER_TAPS; i++) {
        ch->weights[i] += 2.0f * mu_norm * e * ch->delay[k];
        k = (k == 0) ? (ANC_FILTER_TAPS - 1) : (k - 1);
    }

    ch->head = (ch->head + 1) % ANC_FILTER_TAPS;
    return y;
}


/* ══════════════════════════════════════════════════════════
 *  AUDIO PROCESSING BLOCKS
 * ══════════════════════════════════════════════════════════ */

/* Mode 0 — pure passthrough, no processing */
static void process_passthrough(const AdcFrame *in, DacFrame *out)
{
    for (uint32_t n = 0; n < ANC_BLOCK_SIZE; n++) {
        out[n].left  = in[n].src_l;
        out[n].right = in[n].src_r;
    }
}

/*
 * Mode 2 & 3 — digital ANC
 * ref = outer MEMS mic (feedforward reference)
 * src = source audio in (used as error proxy — see lms_process note)
 * out = src - anti_noise
 */
static void process_digital_anc(const AdcFrame *in, DacFrame *out,
                                 uint8_t enable_pwm_out)
{
    for (uint32_t n = 0; n < ANC_BLOCK_SIZE; n++) {
        float32_t ref_l = adc_to_float(in[n].ref_l);
        float32_t ref_r = adc_to_float(in[n].ref_r);
        float32_t src_l = adc_to_float(in[n].src_l);
        float32_t src_r = adc_to_float(in[n].src_r);

        float32_t anti_l = lms_process(&lms_left,  ref_l, src_l);
        float32_t anti_r = lms_process(&lms_right, ref_r, src_r);

        out[n].left  = float_to_dac(src_l - anti_l);
        out[n].right = float_to_dac(src_r - anti_r);

        /* Mode 3: send combined outer mics as mono to TRRS → laptop */
        if (enable_pwm_out) {
            float32_t mono = (ref_l + ref_r) * 0.5f;
            uint16_t pwm_val = (uint16_t)((mono + 1.0f) * 0.5f * PWM_PERIOD);
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, pwm_val);
        }
    }
}

/* Mode 1 — analog ANC: STM32 does nothing, LF356 subcircuit handles it.
 * DAC outputs midpoint (silence) so it doesn't interfere. */
static void process_analog_anc(DacFrame *out)
{
    for (uint32_t n = 0; n < ANC_BLOCK_SIZE; n++) {
        out[n].left  = DAC_MIDPOINT;
        out[n].right = DAC_MIDPOINT;
    }
}


/* ══════════════════════════════════════════════════════════
 *  AD_CTRL SWITCHING
 * ══════════════════════════════════════════════════════════ */
static void set_ad_ctrl(uint8_t digital)
{
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_4,
                      digital ? GPIO_PIN_SET : GPIO_PIN_RESET);
}


/* ══════════════════════════════════════════════════════════
 *  MODE SWITCHING
 * ══════════════════════════════════════════════════════════ */
static void apply_mode(AnuraMode mode)
{
    switch (mode) {
        case MODE_PASSTHROUGH:
            set_ad_ctrl(1);   /* digital path so STM32 can pass audio through */
            break;
        case MODE_ANALOG_ANC:
            set_ad_ctrl(0);   /* hand off to LF356 analog subcircuit */
            break;
        case MODE_DIGITAL_ANC:
            set_ad_ctrl(1);
            lms_init(&lms_left);    /* reset weights on mode entry */
            lms_init(&lms_right);
            break;
        case MODE_TRANSLATION:
            set_ad_ctrl(1);
            lms_init(&lms_left);
            lms_init(&lms_right);
            HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
            break;
    }
}


/* ══════════════════════════════════════════════════════════
 *  DMA CALLBACKS — called from ISR, must be fast
 * ══════════════════════════════════════════════════════════ */
static void dispatch_block(const AdcFrame *in, DacFrame *out)
{
    switch (current_mode) {
        case MODE_PASSTHROUGH:
            process_passthrough(in, out);
            break;
        case MODE_ANALOG_ANC:
            process_analog_anc(out);
            break;
        case MODE_DIGITAL_ANC:
            process_digital_anc(in, out, 0);
            break;
        case MODE_TRANSLATION:
            process_digital_anc(in, out, 1);
            break;
    }
}

void HAL_ADC_ConvHalfCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1)
        dispatch_block(&adc_buf[0], &dac_buf[0]);
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance == ADC1)
        dispatch_block(&adc_buf[ANC_BLOCK_SIZE], &dac_buf[ANC_BLOCK_SIZE]);
}


/* ══════════════════════════════════════════════════════════
 *  BUTTON HANDLING
 *  PA8, active HIGH, debounced via TIM4 1ms tick
 * ══════════════════════════════════════════════════════════ */
static volatile uint32_t btn_tick        = 0;
static volatile uint8_t  btn_last_state  = 0;
static volatile uint8_t  btn_pending     = 0;

/* Call from TIM4 period elapsed callback (1ms) */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM4) return;

    uint8_t state = HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_8);

    if (state && !btn_last_state) {
        /* rising edge — start debounce timer */
        btn_tick = 0;
    }
    if (state) {
        btn_tick++;
        if (btn_tick == BUTTON_DEBOUNCE_MS && !btn_pending) {
            btn_pending = 1;
        }
    } else {
        btn_tick = 0;
    }
    btn_last_state = state;
}

static void button_check(void)
{
    if (!btn_pending) return;
    btn_pending = 0;

    AnuraMode next = (AnuraMode)((current_mode + 1) % NUM_MODES);

    /* Stop PWM if leaving translation mode */
    if (current_mode == MODE_TRANSLATION)
        HAL_TIM_PWM_Stop(&htim3, TIM_CHANNEL_3);

    current_mode = next;
    apply_mode(next);
}


