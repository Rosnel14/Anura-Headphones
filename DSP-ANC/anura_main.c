/*
 * anura_main.c  ——  Complete Anura Signal Board Firmware
 * ───────────────────────────────────────────────────────
 * MCU    : STM32F407VGT6
 * Board  : Anura Signal Board (Leyva-Cortes, Hu, Kepecs)
 *
 * ── Pin mapping ──────────────────────────────────────────
 *  PA2  ADC1_IN2  → LEFT_OUTER_MIC_IN   (MEMS FF reference L)
 *  PA3  ADC1_IN3  → RIGHT_OUTER_MIC_IN  (MEMS FF reference R)
 *  PA6  ADC1_IN6  → LEFT_AUDIO_IN       (source audio + error ref L)
 *  PA7  ADC1_IN7  → RIGHT_AUDIO_IN      (source audio + error ref R)
 *  PA4  DAC_OUT1  → LEFT_AUDIO_OUT
 *  PA5  DAC_OUT2  → RIGHT_AUDIO_OUT
 *  PA8  GPIO_IN   → MODE_BUTTON_IN      (active HIGH, debounced)
 *  PB0  TIM3_CH3  → MONO_MIC_PWM_OUT   (→ RC filter → TRRS → laptop)
 *  PB4  GPIO_OUT  → AD_CTRL_OUT         (HIGH = digital, LOW = analog)
 *  PB6  I2C1_SCL  → OLED + BMS SCL
 *  PB7  I2C1_SDA  → OLED + BMS SDA
 *
 * ── Modes (button cycles 0→1→2→3→0) ─────────────────────
 *  0 — Passthrough   : audio in → audio out, no processing
 *  1 — Analog ANC    : AD_CTRL LOW, LF356 subcircuit handles it
 *  2 — Digital ANC   : NLMS feedforward, outer MEMS mics
 *  3 — Translation   : digital ANC + PWM out → laptop
 *
 * ── Build flags ──────────────────────────────────────────
 *  -DARM_MATH_CM4 -mfpu=fpv4-sp-d16 -mfloat-abi=hard -O2
 *
 * ── CubeMX peripherals needed ────────────────────────────
 *  ADC1  scan, 4ch, DMA2 stream0, timer-triggered (TIM2)
 *  DAC   ch1+ch2, DMA, timer-triggered (TIM2)
 *  TIM2  sample rate trigger (ARR=1749 for 48kHz @ 84MHz)
 *  TIM3  PWM CH3 on PB0 (ARR=4095)
 *  TIM4  1ms timebase for button debounce (ARR=83999 @ 84MHz)
 *  I2C1  fast mode 400kHz, PB6/PB7
 *  GPIO  PA8 input pull-down, PB4 output
 * ─────────────────────────────────────────────────────────
 */

